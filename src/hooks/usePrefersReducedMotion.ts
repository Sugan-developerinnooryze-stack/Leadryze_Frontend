import { useEffect, useState } from 'react';

/** First real implementation of the `prefers-reduced-motion` convention
 * documented (but never actually wired up) in DESIGN-SYSTEM.md. Subscribes
 * to live changes so toggling the OS setting updates already-mounted
 * components without a reload. */
export function usePrefersReducedMotion(): boolean {
  const [reduced, setReduced] = useState(() => {
    if (typeof window === 'undefined' || !window.matchMedia) return false;
    return window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  });

  useEffect(() => {
    if (typeof window === 'undefined' || !window.matchMedia) return;
    const mql = window.matchMedia('(prefers-reduced-motion: reduce)');
    const onChange = () => setReduced(mql.matches);
    mql.addEventListener('change', onChange);
    return () => mql.removeEventListener('change', onChange);
  }, []);

  return reduced;
}
